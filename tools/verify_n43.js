/* N-4-3 結構驗證：題庫契約、答案、出處、教具存在、課綱狀態 */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
let fail = 0;
function check(ok, label) { console.log((ok ? 'PASS ' : 'FAIL ') + label); if (!ok) fail++; }
const unit = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/units/G4/N-4-3.json'), 'utf8'));
check(unit.$schema === 'math-app-unit-v1', '$schema = math-app-unit-v1');
check(unit.curriculum_code === 'N-4-3' && unit.grade === 4, 'curriculum_code/grade');
check(unit.question_count === 10, 'question_count = 10');
check(Array.isArray(unit.questions) && unit.questions.length === 10, 'questions.length = 10');
check(/兩步驟|併式/.test(unit.unit_name), 'unit_name 涵蓋兩步驟／併式');
const ids = new Set(), schools = new Set();
let bracket = 0, chain = 0;
unit.questions.forEach((q, i) => {
  const n = 'Q' + String(i + 1).padStart(2, '0');
  check(q.id === 'G4-N-4-3-' + n, n + ' id');
  check(!ids.has(q.id), n + ' id 唯一'); ids.add(q.id);
  check(typeof q.stem === 'string' && q.stem.length > 12, n + ' 題幹完整不閹割');
  check(Array.isArray(q.choices) && q.choices.length === 4, n + ' 4 選項');
  check(new Set(q.choices).size === 4, n + ' 選項不重複');
  check(Number.isInteger(q.answer_index) && q.answer_index >= 0 && q.answer_index < 4, n + ' answer_index 合法');
  check(typeof q.answer_raw === 'string' && q.answer_raw.length > 0, n + ' answer_raw');
  check(typeof q.exam_source === 'string' && /p\d/.test(q.exam_source), n + ' 出處含頁碼');
  check(/國小/.test(q.exam_source), n + ' 出處含學校');
  check(q.component === 'two_step_expr_g4_lab', n + ' component');
  check(q.component_path === 'components/two_step_expr_g4_lab.html?q=' + (i + 1), n + ' component_path ?q 聯動');
  check(q.fallback_height === 420, n + ' fallback_height 420');
  const e = q.explanation || {};
  check(typeof e.concept === 'string' && e.concept.length > 8, n + ' explanation.concept');
  check(Array.isArray(e.steps) && e.steps.length >= 3, n + ' explanation.steps');
  check(typeof e.trap === 'string' && e.trap.length > 8, n + ' explanation.trap');
  const m = q.exam_source.match(/(獅湖|永安|南湖)國小/); if (m) schools.add(m[1]);
  if (/\(/.test(e.steps[2] || '') || /\(/.test(q.title)) bracket++;
  if (/÷.*÷/.test(e.steps[2] || '')) chain++;
});
check(schools.size >= 2, '跨 2 校以上（實 ' + schools.size + '：' + [...schools].join('/') + '）');
check(bracket >= 3, '括號併式題 >= 3（實 ' + bracket + '）');
check(chain >= 1, '連除題 >= 1（實 ' + chain + '）');
const cur = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/curriculum.json'), 'utf8'));
const all = [];
(function walk(o) { if (Array.isArray(o)) o.forEach(walk); else if (o && typeof o === 'object') { if (o.code) all.push(o); Object.values(o).forEach(walk); } })(cur);
const u = all.find(x => x.code === 'N-4-3');
check(!!u && u.status === 'ready', 'curriculum N-4-3 status=ready');
check(!!u && u.question_count === 10, 'curriculum N-4-3 question_count=10');
check(!!u && u.component_path === 'components/two_step_expr_g4_lab.html', 'curriculum component_path');
check(!!u && u.concept_path === 'components/two_step_expr_g4_lab.html', 'curriculum concept_path');
check(fs.existsSync(path.join(ROOT, 'app/components/two_step_expr_g4_lab.html')), '教具檔案存在');
const html = fs.readFileSync(path.join(ROOT, 'app/components/two_step_expr_g4_lab.html'), 'utf8');
check(/height:auto;\s*min-height:0/.test(html) && !/100vh/.test(html), '禁 100vh、採 height:auto/min-height:0');
check(/theme-tokens\.css/.test(html) && /html\[data-theme="dark"\]/.test(html), '接入 theme-tokens 且 Dark 覆寫');
check(/pointerdown/.test(html) && /pointermove/.test(html) && /pointerup/.test(html), '真實 pointerdown/move/up 事件監聽');
check(/URLSearchParams/.test(html) && /parseInt\(P.get\('q'\)/.test(html), '?q=1..10 題目聯動');
console.log(fail === 0 ? 'ALL PASS' : 'FAILED ' + fail);
process.exit(fail === 0 ? 0 : 1);

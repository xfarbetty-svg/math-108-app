/* N-4-2 結構驗證：題庫契約、答案、出處、教具存在、Q7 誤植如實記載 */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
let fail = 0;
function check(ok, label) {
  console.log((ok ? 'PASS ' : 'FAIL ') + label);
  if (!ok) fail++;
}
const unit = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/units/G4/N-4-2.json'), 'utf8'));
check(unit.$schema === 'math-app-unit-v1', '$schema = math-app-unit-v1');
check(unit.curriculum_code === 'N-4-2' && unit.grade === 4, 'curriculum_code/grade');
check(unit.question_count === 10, 'question_count = 10');
check(Array.isArray(unit.questions) && unit.questions.length === 10, 'questions.length = 10');
check(/乘法子範圍/.test(unit.note) && /除法/.test(unit.note), '如實註記僅乘法子範圍、除法另站');
check(/南湖.*內湖|內湖.*南湖/.test(unit.note), '如實註記檔名與卷首校名差異');
const ids = new Set();
const covers = { threeTwo: 0, fourTwo: 0, threeThree: 0, zero: 0, word: 0 };
unit.questions.forEach((q, i) => {
  const n = 'Q' + String(i + 1).padStart(2, '0');
  check(q.id === 'G4-N-4-2-' + n, n + ' id');
  check(!ids.has(q.id), n + ' id 唯一'); ids.add(q.id);
  check(typeof q.stem === 'string' && q.stem.length > 8, n + ' 題幹完整');
  check(Array.isArray(q.choices) && q.choices.length === 4, n + ' 4 選項');
  check(new Set(q.choices).size === 4, n + ' 選項不重複');
  check(Number.isInteger(q.answer_index) && q.answer_index >= 0 && q.answer_index < 4, n + ' answer_index 合法');
  check(typeof q.answer_raw === 'string' && q.answer_raw.length > 0, n + ' answer_raw');
  check(typeof q.exam_source === 'string' && /p\d/.test(q.exam_source), n + ' 出處含頁碼');
  check(q.component === 'g4_mul_lab', n + ' component');
  check(q.component_path === 'components/g4_mul_lab.html?q=' + (i + 1), n + ' component_path ?q 聯動');
  check(q.fallback_height === 420, n + ' fallback_height 420');
  const e = q.explanation || {};
  check(typeof e.concept === 'string' && e.concept.length > 5, n + ' explanation.concept');
  check(Array.isArray(e.steps) && e.steps.length >= 3, n + ' explanation.steps');
  check(typeof e.trap === 'string' && e.trap.length > 5, n + ' explanation.trap');
  if (/三位數×二位數/.test(q.title)) covers.threeTwo++;
  if (/四位數×二位數/.test(q.title)) covers.fourTwo++;
  if (/三位數×三位數/.test(q.title)) covers.threeThree++;
  if (/0/.test(q.title) || /0/.test(q.stem)) covers.zero++;
  if (/應用題/.test(q.section)) covers.word++;
});
check(unit.questions[6].source_anomaly && /① 2 個/.test(unit.questions[6].source_anomaly), 'Q7 原卷誤植如實記載 source_anomaly');
check(unit.questions[6].choices[2] === '2 個', 'Q7 選項③數值逐字保留');
check(covers.zero >= 5, '0 陷阱題 >= 5（實 ' + covers.zero + '）');
check(covers.word >= 1, '文字應用題 >= 1');
const cur = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/curriculum.json'), 'utf8'));
const all = [];
(function walk(o) { if (Array.isArray(o)) { o.forEach(walk); } else if (o && typeof o === 'object') { if (o.code) all.push(o); Object.values(o).forEach(walk); } })(cur);
const u = all.find(x => x.code === 'N-4-2');
check(!!u && u.status === 'ready', 'curriculum N-4-2 status=ready');
check(!!u && u.question_count === 10, 'curriculum N-4-2 question_count=10');
check(!!u && u.component_path === 'components/g4_mul_lab.html', 'curriculum component_path');
check(fs.existsSync(path.join(ROOT, 'app/components/g4_mul_lab.html')), '教具檔案存在');
const html = fs.readFileSync(path.join(ROOT, 'app/components/g4_mul_lab.html'), 'utf8');
check(/height:auto;\s*min-height:0/.test(html) && !/100vh/.test(html), '禁 100vh、採 height:auto/min-height:0');
check(/theme-tokens\.css/.test(html) && /html\[data-theme="dark"\]/.test(html), '接入 theme-tokens 且 Dark 覆寫');
check(/pointerdown|onclick|addEventListener/.test(html), '具真實事件監聽');
console.log(fail === 0 ? 'ALL PASS' : 'FAILED ' + fail);
process.exit(fail === 0 ? 0 : 1);
